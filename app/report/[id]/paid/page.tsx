import { notFound, redirect } from 'next/navigation'
import { createClient } from '@/lib/supabase/server'
import { StarsBackground } from '@/components/stars-background'
import { PaidReportContent } from '@/components/paid-report-content'
import type { Submission } from '@/lib/types'

interface PageProps {
  params: Promise<{ id: string }>
}

export async function generateMetadata({ params }: PageProps) {
  const { id } = await params
  const supabase = await createClient()
  
  const { data } = await supabase
    .from('submissions')
    .select('name')
    .eq('id', id)
    .single()
  
  return {
    title: data ? `${data.name}'s Full 99 Facts Report - Sajume` : 'Full Report - Sajume',
    description: 'Your complete 99 facts saju birth chart analysis'
  }
}

export default async function PaidReportPage({ params }: PageProps) {
  const { id } = await params
  
  // Validate UUID format
  const uuidRegex = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
  if (!uuidRegex.test(id)) {
    notFound()
  }
  
  const supabase = await createClient()
  
  // Check payment status and fetch data in parallel
  // IMPORTANT: section_key='paid_full' is the only valid paid report (generated by generate-paid-report API)
  // Other is_free=false rows are per-section fallbacks from generate-section and should be ignored
  const [submissionResult, paymentResult, paidReportResult] = await Promise.all([
    supabase.from('submissions').select('*').eq('id', id).single(),
    supabase.from('payments').select('*').eq('submission_id', id).eq('status', 'completed').single(),
    supabase.from('reports').select('*').eq('submission_id', id).eq('section_key', 'paid_full').single()
  ])
  
  if (!submissionResult.data) {
    notFound()
  }
  
  // Payment must be completed to view paid report
  if (!paymentResult.data) {
    redirect(`/checkout/${id}`)
  }
  
  // If paid report doesn't exist yet, generate it now by calling the API
  let paidReport = paidReportResult.data
  if (!paidReport) {
    console.log('[v0] No paid report found, generating via API...')
    const baseUrl = process.env.VERCEL_URL 
      ? `https://${process.env.VERCEL_URL}` 
      : process.env.NEXT_PUBLIC_BASE_URL || 'http://localhost:3000'
    
    try {
      const response = await fetch(`${baseUrl}/api/generate-paid-report`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ submissionId: id }),
        cache: 'no-store'
      })
      
      if (response.ok) {
        const result = await response.json()
        console.log('[v0] Paid report generated, facts count:', result.facts?.length)
        // Refetch the paid report from DB
        const { data: freshReport } = await supabase
          .from('reports')
          .select('*')
          .eq('submission_id', id)
          .eq('section_key', 'paid_full')
          .single()
        paidReport = freshReport
      } else {
        console.error('[v0] Failed to generate paid report:', await response.text())
      }
    } catch (error) {
      console.error('[v0] Error generating paid report:', error)
    }
  }

  // If still no paid report after generation attempt, show error
  if (!paidReport) {
    return (
      <main className="min-h-screen bg-mystical flex items-center justify-center">
        <div className="text-center text-white">
          <h1 className="text-2xl font-bold mb-4">Report Generation In Progress</h1>
          <p className="text-white/60 mb-4">Your 99 facts report is being generated. This may take up to 60 seconds.</p>
          <p className="text-white/40 text-sm">Please refresh this page in a moment.</p>
        </div>
      </main>
    )
  }
  
  return (
    <main className="min-h-screen bg-mystical relative overflow-hidden">
      <StarsBackground />
      
      <div className="relative z-10">
        <PaidReportContent 
          submission={submissionResult.data as Submission}
          paidReport={paidReport}
        />
      </div>
    </main>
  )
}
